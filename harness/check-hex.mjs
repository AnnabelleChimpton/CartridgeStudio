// Fails on any hex colour outside the generated palette. Every colour in the
// app, the site and the player page is an NTSC palette entry named in
// app/src/ui/tokens.ts; this keeps a stray "#ff8a5c" from creeping back in.
//
//   node harness/check-hex.mjs
//
// Allowed: ui/ntsc.ts (it computes the palette), the files
// app/scripts/make-identity.mjs writes (tokens.css, the tokens block in
// site/styles.css, the icons, the manifest and the theme-color meta), tests,
// and vendored or font files.

import { readFileSync, readdirSync, statSync } from "node:fs";
import { join, relative, extname } from "node:path";
import { fileURLToPath } from "node:url";
import { execFileSync } from "node:child_process";

const root = join(fileURLToPath(new URL(".", import.meta.url)), "..");
const SCAN = ["app/src", "app/public", "app/index.html", "app/organize.html", "site"];
// site/play holds exported player pages that app/scripts/make-site.test.ts writes;
// their colours come from tokens.ts through player.ts, which this check covers.
const SKIP_DIRS = new Set(["node_modules", "vendor", "fonts", "clips", "play"]);
const EXTS = new Set([".css", ".ts", ".tsx", ".js", ".mjs", ".html", ".svg", ".json", ".webmanifest"]);
const GENERATED_MARK = "Generated by app/scripts/make-identity.mjs";
const ALLOWED_FILES = new Set(["app/src/ui/ntsc.ts", "app/public/manifest.webmanifest", "site/fonts.css"]);
// A hex colour: # and 3, 4, 6 or 8 hex digits, not part of an HTML entity (&#123;) or a longer word.
const HEX = /(?<![&\w])#(?:[0-9a-fA-F]{8}|[0-9a-fA-F]{6}|[0-9a-fA-F]{3,4})(?![\w-])/g;

function* files(path) {
  const full = join(root, path);
  let st;
  try {
    st = statSync(full);
  } catch {
    return;
  }
  if (st.isFile()) return void (yield path);
  for (const name of readdirSync(full)) {
    if (SKIP_DIRS.has(name)) continue;
    yield* files(join(path, name));
  }
}

const problems = [];
for (const top of SCAN) {
  for (const path of files(top)) {
    const rel = relative(".", path);
    if (!EXTS.has(extname(path)) || ALLOWED_FILES.has(rel) || /\.test\.tsx?$/.test(path)) continue;
    let text = readFileSync(join(root, path), "utf8");
    if (text.slice(0, 300).includes(GENERATED_MARK)) continue;
    // The generated tokens block in site/styles.css.
    text = text.replace(/\/\* tokens:start[^]*?tokens:end \*\//, (m) => m.replace(/[^\n]/g, " "));
    // The generated theme-color.
    text = text.replace(/<meta name="theme-color" content="#[0-9a-fA-F]{6}"\s*\/?>/g, (m) => " ".repeat(m.length));
    text.split("\n").forEach((line, i) => {
      for (const m of line.matchAll(HEX)) problems.push(`${rel}:${i + 1}: ${m[0]}`);
    });
  }
}

// And the generated files match tokens.ts and brand.ts.
try {
  execFileSync(process.execPath, [join(root, "app/scripts/make-identity.mjs"), "--check"], { stdio: "inherit" });
} catch {
  process.exit(1);
}

if (problems.length) {
  console.error(`Hex colours outside the palette tokens (use a token from app/src/ui/tokens.ts):\n${problems.join("\n")}`);
  process.exit(1);
}
console.log("No stray hex colours.");
