import { strFromU8, strToU8, unzipSync, unzlibSync, zipSync } from "fflate";
import { describe, expect, it } from "vitest";
import type { Project } from "../project/schema.ts";
import { TEMPLATES, getTemplate } from "../project/templates.ts";
import { readCartridgeFile, writeCartridgeFile } from "./cartridge-file.ts";
import { checklist, slugify, sourceZip, submissionZip } from "./exports.ts";
import { encodeRgbaPng } from "./png.ts";

const template = getTemplate("fixed-shooter");
const sample = () => structuredClone(template.sample);

describe("encodeRgbaPng", () => {
  it("writes a valid 8-bit RGBA PNG", () => {
    const rgba = new Uint8Array(4 * 3 * 4).map((_, i) => i);
    const png = encodeRgbaPng(4, 3, rgba);
    expect([...png.subarray(0, 8)]).toEqual([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a]);
    const dv = new DataView(png.buffer);
    expect([dv.getUint32(16), dv.getUint32(20), png[24], png[25]]).toEqual([4, 3, 8, 6]);
    // IDAT holds 3 rows of (filter byte + 16 bytes).
    const idatLength = dv.getUint32(33);
    const raw = unzlibSync(png.subarray(41, 41 + idatLength));
    expect(raw.length).toBe(3 * 17);
    expect([...raw.subarray(1, 17)]).toEqual([...rgba.subarray(0, 16)]);
  });
});

describe(".cartridge files", () => {
  it("round-trips a project and its thumbnail", () => {
    const p = sample();
    p.title = "Moth Patrol";
    const thumb = encodeRgbaPng(2, 2, new Uint8Array(16).fill(200));
    const opened = readCartridgeFile(writeCartridgeFile(p, thumb), TEMPLATES);
    expect(opened.result).toEqual({ ok: true, project: p });
    expect(opened.thumbnail).toEqual(thumb);
  });

  it("is identical for identical projects", () => {
    expect(writeCartridgeFile(sample())).toEqual(writeCartridgeFile(sample()));
  });

  it("upgrades games saved with an older template", () => {
    const old: Project = sample();
    old.template.version = "0.1.0";
    old.sprites.find((s) => s.role === "enemy")!.frames.splice(1);
    const opened = readCartridgeFile(writeCartridgeFile(old), TEMPLATES);
    expect(opened.result.ok && "project" in opened.result && opened.result.project.template.version).toBe(template.manifest.version);
  });

  it("refuses files that aren't game files", () => {
    const err = (bytes: Uint8Array) => {
      const r = readCartridgeFile(bytes, TEMPLATES).result;
      return r.ok ? null : r.errors[0];
    };
    expect(err(strToU8("hello"))).toBe("This isn't a Cartridge Studio game file.");
    expect(err(zipSync({ "project.json": strToU8("{}") }))).toBe("This isn't a Cartridge Studio game file.");
    expect(
      err(zipSync({ "cartridge.json": strToU8('{"format":"cartridge-studio","version":9}'), "project.json": strToU8("{}") })),
    ).toBe("This game file was saved by a newer version of Cartridge Studio.");
    expect(
      err(zipSync({ "cartridge.json": strToU8('{"format":"cartridge-studio","version":1}'), "project.json": strToU8("{oops") })),
    ).toBe("This game file is damaged.");
  });
});

describe("exports", () => {
  it("exports game.bas, every graphic and a README", () => {
    const files = unzipSync(sourceZip(sample(), template));
    expect(Object.keys(files).sort()).toEqual(
      ["README.txt", "bomb.png", "enemy.png", "enemy_1.png", "font.png", "game.bas", "player.png", "shot.png"].map(
        (n) => `cat-vs-vacuums-source/${n}`,
      ),
    );
    expect(strFromU8(files["cat-vs-vacuums-source/game.bas"]!)).toMatch(/^ rem Cat vs\. Vacuums - generated by Cartridge Studio/);
  });

  it("packs a submission with ROMs, PDF, game file, source and checklist", () => {
    const p = sample();
    const zip = submissionZip({
      project: p,
      template,
      a78: new Uint8Array([1]),
      bin: new Uint8Array([2]),
      pdf: strToU8("%PDF-"),
      cartridgeFile: writeCartridgeFile(p),
    });
    const names = Object.keys(unzipSync(zip)).map((n) => n.replace("cat-vs-vacuums-submission/", ""));
    expect(names).toEqual(
      expect.arrayContaining([
        "CHECKLIST.txt",
        "rom/cat-vs-vacuums.bin",
        "rom/cat-vs-vacuums.a78",
        "print/cat-vs-vacuums-print.pdf",
        "project/cat-vs-vacuums.cartridge",
        "source/game.bas",
        "source/enemy_1.png",
      ]),
    );
  });

  it("writes a checklist naming the files and the toolchain", () => {
    const text = checklist(sample(), template);
    expect(text).toContain("rom/cat-vs-vacuums.bin");
    expect(text).toContain("7800basic 0.41");
    expect(text).toContain("Not affiliated with or endorsed by Atari.");
    expect(slugify("  Moth Patrol! 2 ")).toBe("moth-patrol-2");
    expect(slugify("🐱")).toBe("game");
  });
});
