import { describe, expect, it } from "vitest";
import { SOUND_LIBRARY } from "../project/templates.ts";
import { generateKit } from "./generate.ts";
import { KIT_PRESETS } from "./presets.ts";

const ghostPanic = () => structuredClone(KIT_PRESETS.find((p) => p.id === "ghost-panic")!.game);
const source = (game: unknown) => {
  const r = generateKit(game, SOUND_LIBRARY);
  if (!r.ok) throw new Error(r.errors.join("\n"));
  return r.input.source;
};

describe('"Made by" on the title screen', () => {
  it("puts BY and the maker under the title, centred, and names them in the header", () => {
    const s = source({ ...ghostPanic(), madeBy: "Sam and Robin" });
    expect(s).toContain(" plotchars 'BY SAM AND ROBIN' ");
    expect(s.split("\n")[0]).toMatch(/^ rem Ghost Panic, by Sam and Robin - generated by Cartridge Studio/);
    // 16 characters in 4-pixel cells, centred on the 160-pixel screen, one row under the title.
    expect(s).toMatch(/plotchars 'BY SAM AND ROBIN' \d+ 48 10/);
  });

  it("draws only what the font has, and nothing at all when it's not filled in", () => {
    expect(source({ ...ghostPanic(), madeBy: "Sam & Robin" })).toContain(" plotchars 'BY SAM ROBIN' ");
    const none = source(ghostPanic());
    expect(none).not.toContain("'BY ");
    expect(none.split("\n")[0]).not.toContain(", by");
  });
});
