import fs from "node:fs";
import path from "node:path";
import { beforeAll, describe, expect, it } from "vitest";
import { TOOLCHAIN_PACK_FILE, WasiBuilder, readPack } from "@cartridge-studio/toolchain";
import { getTemplate } from "../project/templates.ts";
import type { Project } from "../project/schema.ts";
import { actionLabel, generate, sanitizeTitle } from "./generate.ts";
import { lintBasic } from "./lint.ts";

const template = getTemplate("fixed-shooter");
const sample = template.sample;
const clone = (): Project => structuredClone(sample);

function gen(project: unknown) {
  const r = generate(project, template);
  if (!r.ok) throw new Error(r.errors.join("\n"));
  return r.input;
}

describe("generate", () => {
  it("renders the sample project (snapshot)", async () => {
    await expect(gen(sample).source).toMatchFileSnapshot("__snapshots__/fixed-shooter-sample.bas");
  });

  it("is deterministic", () => {
    const a = gen(sample);
    const b = gen(clone());
    expect(a.source).toBe(b.source);
    expect(a.files).toEqual(b.files);
  });

  it("emits one PNG per sprite frame", () => {
    expect(Object.keys(gen(sample).files).sort()).toEqual(["bomb.png", "enemy.png", "enemy_1.png", "font.png", "player.png", "shot.png"]);
  });

  it("clamps and snaps params to the manifest ranges", () => {
    const p = clone();
    p.params.enemySpeed = 99;
    p.params.pointsPerEnemy = 44;
    p.params.lives = -3;
    const src = gen(p).source;
    expect(src).toContain("const STARTINTERVAL = 3"); // 13 - 10
    expect(src).toContain("const POINTS = $40");
    expect(src).toContain("const STARTLIVES = 1");
  });

  it("uses defaults for missing params", () => {
    const p = clone();
    p.params = {};
    expect(gen(p).source).toContain("const SHIPSPEED = 2");
  });

  it("renders each rule into its hook with a comment naming it", () => {
    const src = gen(sample).source;
    expect(src).toMatch(/hook_input_fire\n rem rule 2: input\.fire -> player\.shoot\n gosub action_player_shoot\n return/);
  });

  it("falls back to the hook's default when no rule uses it", () => {
    const p = clone();
    p.rules = p.rules.filter((r) => r.when !== "enemies.cleared");
    const src = gen(p).source;
    expect(src).toMatch(/hook_enemies_cleared\n rem no rule for this trigger[^\n]*\n gosub setupwave\n return/);
    expect(src).not.toContain("action_wave_next");
  });

  it("only includes the actions the rules use", () => {
    const p = clone();
    p.rules = [{ when: "input.fire", then: ["player.shoot"] }];
    const src = gen(p).source;
    expect(src).toContain("action_player_shoot\n");
    expect(src).not.toContain("action_score_add");
  });

  it("maps palettes to registers in project order", () => {
    const p = clone();
    p.palettes.reverse();
    const src = gen(p).source;
    expect(src).toContain(" P0C1 = $0F : P0C2 = $0F : P0C3 = $0F"); // hud is now first
    expect(src).toContain("plotsprite player 4 playerx ey");
  });

  it("keeps the title on its rem line", () => {
    const p = clone();
    p.title = "Evil\n goto 0 : rem";
    expect(gen(p).source.split("\n")[0]).toBe(" rem Evil goto 0 rem - generated by Cartridge Studio");
    expect(sanitizeTitle("")).toBe("Untitled");
  });
});

describe("validation", () => {
  const errors = (mutate: (p: Project) => void) => {
    const p = clone();
    mutate(p);
    const r = generate(p, template);
    return r.ok ? [] : r.errors;
  };

  it("rejects a sprite of the wrong size", () => {
    expect(errors((p) => (p.sprites[0]!.width = 8))).toContain('"Player ship" must be 16×16 pixels.');
  });
  it("rejects a missing role", () => {
    expect(errors((p) => (p.sprites = p.sprites.filter((s) => s.role !== "bomb")))).toContain(
      'The game needs a sprite for "Enemy bomb".',
    );
  });
  it("rejects damaged pixels", () => {
    expect(errors((p) => (p.sprites[1]!.frames[0]![0] = "00000000000x"))).toContain(
      'The pixels of "Enemy" (frame 1) are damaged.',
    );
  });
  it("rejects rules outside the vocabulary", () => {
    expect(errors((p) => p.rules.push({ when: "player.jumps", then: ["lives.lose"] }))).toContain(
      'Rule 5 uses "player.jumps", which this template doesn\'t understand.',
    );
    expect(errors((p) => p.rules.push({ when: "input.fire", then: ["rom.erase"] }))).toContain(
      'Rule 5 uses the action "rom.erase", which this template doesn\'t have.',
    );
  });
  it("rejects too many palettes", () => {
    expect(
      errors((p) => {
        for (let i = 0; i < 4; i++) p.palettes.push({ id: `extra-${i}`, colors: ["$00", "$00", "$00"] });
      }),
    ).toContain("A game can use at most 8 palettes; this one has 9.");
  });
  it("rejects unknown settings and damaged files", () => {
    expect(errors((p) => (p.params.gravity = 3))).toContain('"gravity" isn\'t a setting this template has.');
    expect(generate({ schema: 1 }, template).ok).toBe(false);
  });
});

describe("template fixed-shooter", () => {
  it("has a snippet defining each action's label and returning", () => {
    for (const a of template.manifest.actions) {
      const snippet = template.actions[a.id];
      expect(snippet, a.id).toBeDefined();
      expect(snippet!.startsWith(`${actionLabel(a.id)}\n`), a.id).toBe(true);
      expect(snippet!.trimEnd().endsWith(" return"), a.id).toBe(true);
    }
  });

  it("sample uses the template's own version and default params", () => {
    expect(sample.template).toEqual({ id: template.manifest.id, version: template.manifest.version });
    for (const p of template.manifest.params) expect(sample.params[p.id], p.id).toBe(p.default);
  });
});

describe("lint", () => {
  const src = (body: string) => ` const K = 20\n const Y = 168\n${body}\n`;
  it("flags multiplying by a const", () => {
    expect(lintBasic(src(" a = b * K"))).toHaveLength(1);
    expect(lintBasic(src(" a = b * 20"))).toHaveLength(0);
  });
  it("flags score math with a const that isn't BCD", () => {
    expect(lintBasic(" const P = 30\n score0 = score0 + P\n")).toHaveLength(1);
    expect(lintBasic(" const P = $30\n score0 = score0 + P\n")).toHaveLength(0);
  });
  it("flags consts as plotsprite and boxcollision positions", () => {
    expect(lintBasic(src(" plotsprite ship 0 x Y"))).toHaveLength(1);
    expect(lintBasic(src(" if boxcollision(a, b, 4, 4, x, Y, 16, 16) then c = 1"))).toHaveLength(1);
    expect(lintBasic(src(" plotsprite ship 0 x y : a = K"))).toHaveLength(0);
  });
  it("passes the sample's generated code", () => {
    expect(lintBasic(gen(sample).source)).toEqual([]);
  });
});

describe("generated code compiles", () => {
  let builder: WasiBuilder;
  beforeAll(async () => {
    const pack = path.resolve(import.meta.dirname, "../../../toolchain/vendor", TOOLCHAIN_PACK_FILE);
    builder = await WasiBuilder.create(readPack(fs.readFileSync(pack)));
  });

  const variants: Record<string, (p: Project) => void> = {
    sample: () => {},
    "min params": (p) => {
      for (const d of template.manifest.params) p.params[d.id] = d.min;
    },
    "max params": (p) => {
      for (const d of template.manifest.params) p.params[d.id] = d.max;
    },
    "no rules": (p) => (p.rules = []),
    "every action on every trigger": (p) =>
      (p.rules = template.manifest.triggers.map((t) => ({ when: t.id, then: template.manifest.actions.map((a) => a.id) }))),
  };

  for (const [name, mutate] of Object.entries(variants)) {
    it(name, async () => {
      const p = clone();
      mutate(p);
      const result = await builder.build(gen(p));
      if (!result.ok) throw new Error(`${result.stage}: ${result.message}\n${result.log}`);
      expect(result.bin.length).toBe(32 * 1024);
    });
  }
});
