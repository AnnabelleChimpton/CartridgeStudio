// Writes everything that carries the palette or the mark, from src/ui/tokens.ts
// and src/ui/brand.ts:
//   app/src/tokens.css, the tokens block in site/styles.css,
//   the manifest's colours and every page's theme-color,
//   app/public/icons (icon.svg, the PNGs, the maskable icon),
//   site/icons/mark.svg, the site favicon and its header mark.
//
//   node app/scripts/make-identity.mjs          write them
//   node app/scripts/make-identity.mjs --check  exit 1 if any is out of date

import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";
import { deflateSync } from "node:zlib";
import { tokensCss, PAGE, SEMANTIC, hex } from "../src/ui/tokens.ts";
import { markRects, MARK_GRID } from "../src/ui/brand.ts";

const root = join(dirname(fileURLToPath(import.meta.url)), "..", "..");
const check = process.argv.includes("--check");
const stale = [];

function put(path, content) {
  const file = join(root, path);
  let old = null;
  try {
    old = readFileSync(file);
  } catch {}
  const next = typeof content === "string" ? Buffer.from(content) : content;
  if (old && Buffer.compare(old, next) === 0) return;
  if (check) return void stale.push(path);
  mkdirSync(dirname(file), { recursive: true });
  writeFileSync(file, next);
  console.log("wrote", relative(root, file));
}

/** Rewrites `path` with `edit`, if it exists. */
function patch(path, edit) {
  let text;
  try {
    text = readFileSync(join(root, path), "utf8");
  } catch {
    return;
  }
  put(path, edit(text));
}

const GENERATED = "Generated by app/scripts/make-identity.mjs from app/src/ui/tokens.ts. Don't edit; change tokens.ts and rerun it.";

// Tokens --------------------------------------------------------------------

put("app/src/tokens.css", `/* ${GENERATED} */\n${tokensCss()}`);
patch("site/styles.css", (css) =>
  css.replace(/\/\* tokens:start[^]*?tokens:end \*\//, `/* tokens:start. ${GENERATED} */\n${tokensCss()}/* tokens:end */`),
);
patch("app/public/manifest.webmanifest", (json) =>
  json.replace(/("background_color": ")[^"]*"/, `$1${PAGE}"`).replace(/("theme_color": ")[^"]*"/, `$1${PAGE}"`),
);
for (const page of ["app/index.html", "app/organize.html", "site/index.html"]) {
  patch(page, (html) => html.replace(/(<meta name="theme-color" content=")[^"]*(")/, `$1${PAGE}$2`));
}

// The mark --------------------------------------------------------------------

const rects = markRects();

/** The mark as SVG; `fill` gives each role's colour, `bg` an optional backdrop, `pad` grid cells around it. */
function markSvg({ fill, bg, pad = 0, comment = true }) {
  const size = MARK_GRID + pad * 2;
  const body = rects.map((r) => `<rect x="${r.x}" y="${r.y}" width="${r.w}" height="${r.h}" fill="${fill(r.role)}"/>`).join("");
  const back = bg ? `<rect x="${-pad}" y="${-pad}" width="${size}" height="${size}" fill="${bg}"/>` : "";
  const note = comment ? `<!-- ${GENERATED} -->` : "";
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${-pad} ${-pad} ${size} ${size}" shape-rendering="crispEdges">${note}${back}${body}</svg>\n`;
}

const colour = (role) => hex(SEMANTIC[role]);
put("app/public/icons/icon.svg", markSvg({ fill: colour, bg: PAGE }));
// Maskable: the whole mark inside the 80% safe circle (corner at 0.39 of the width from centre).
put("app/public/icons/icon-maskable.svg", markSvg({ fill: colour, bg: PAGE, pad: 4.8 }));
put("site/icons/mark.svg", markSvg({ fill: colour }));

// PNGs, drawn pixel for pixel: `scale` screen pixels per grid cell, `offset` px of page colour around it.
function png(size, scale, offset) {
  const rgb = (h) => [1, 3, 5].map((i) => parseInt(h.slice(i, i + 2), 16));
  const px = new Uint8Array(size * size * 4);
  const fillRect = (x0, y0, w, h, c) => {
    for (let y = Math.max(0, y0); y < Math.min(size, y0 + h); y++)
      for (let x = Math.max(0, x0); x < Math.min(size, x0 + w); x++) px.set([...c, 255], (y * size + x) * 4);
  };
  fillRect(0, 0, size, size, rgb(PAGE));
  for (const r of rects) fillRect(offset + r.x * scale, offset + r.y * scale, r.w * scale, r.h * scale, rgb(colour(r.role)));
  const raw = Buffer.alloc(size * (size * 4 + 1));
  for (let y = 0; y < size; y++) Buffer.from(px.buffer, y * size * 4, size * 4).copy(raw, y * (size * 4 + 1) + 1);
  const crcTable = Array.from({ length: 256 }, (_, n) => {
    let c = n;
    for (let k = 0; k < 8; k++) c = c & 1 ? 0xedb88320 ^ (c >>> 1) : c >>> 1;
    return c >>> 0;
  });
  const crc = (buf) => {
    let c = 0xffffffff;
    for (const b of buf) c = crcTable[(c ^ b) & 0xff] ^ (c >>> 8);
    return (c ^ 0xffffffff) >>> 0;
  };
  const chunk = (type, data) => {
    const len = Buffer.alloc(4);
    len.writeUInt32BE(data.length);
    const td = Buffer.concat([Buffer.from(type), data]);
    const sum = Buffer.alloc(4);
    sum.writeUInt32BE(crc(td));
    return Buffer.concat([len, td, sum]);
  };
  const ihdr = Buffer.alloc(13);
  ihdr.writeUInt32BE(size, 0);
  ihdr.writeUInt32BE(size, 4);
  ihdr.set([8, 6, 0, 0, 0], 8);
  return Buffer.concat([
    Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a]),
    chunk("IHDR", ihdr),
    chunk("IDAT", deflateSync(raw, { level: 9 })),
    chunk("IEND", Buffer.alloc(0)),
  ]);
}

put("app/public/icons/icon-192.png", png(192, 12, 0));
put("app/public/icons/icon-512.png", png(512, 32, 0));
put("app/public/icons/apple-touch-icon.png", png(180, 11, 2));
put("app/public/icons/icon-maskable-512.png", png(512, 20, 96));
put("app/public/icons/favicon-32.png", png(32, 2, 0));

// The site: favicon and header mark from the same rects, coloured by the site's tokens.
patch("site/index.html", (html) =>
  html
    .replace(/<link rel="icon"[^>]*>/, `<link rel="icon" href="icons/mark.svg" type="image/svg+xml">`)
    .replace(
      /<svg class="brand-mark"[^]*?<\/svg>/,
      markSvg({ fill: (role) => `var(--${role})`, comment: false })
        .trim()
        .replace("<svg ", `<svg class="brand-mark" aria-hidden="true" focusable="false" `),
    ),
);

if (check && stale.length) {
  console.error(`Out of date: ${stale.join(", ")}. Run: node app/scripts/make-identity.mjs`);
  process.exit(1);
}
